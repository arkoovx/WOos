static inline const uint8_t* glyph_for_unicode(uint32_t cp) {
    if (cp < 128) {
        return g_font_cp866[cp];
    }
    // Russian uppercase: U+0410 (А) .. U+042F (Я)
    if (cp >= 0x0410 && cp <= 0x042F) {
        return g_font_cp866[0x80 + (cp - 0x0410)];
    }
    // Russian lowercase: U+0430 (а) .. U+043F (п)
    if (cp >= 0x0430 && cp <= 0x043F) {
        return g_font_cp866[0xA0 + (cp - 0x0430)];
    }
    // Russian lowercase: U+0440 (р) .. U+044F (я)
    if (cp >= 0x0440 && cp <= 0x044F) {
        return g_font_cp866[0xE0 + (cp - 0x0440)];
    }
    // Russian Ё / ё
    if (cp == 0x0401) return g_font_cp866[0xF0];
    if (cp == 0x0451) return g_font_cp866[0xF1];
    // Punctuation
    if (cp == 0x2116) return g_font_cp866[0xFC]; // №
    if (cp == 0x00AB) return g_font_cp866[0xAE]; // «
    if (cp == 0x00BB) return g_font_cp866[0xAF]; // »
    if (cp == 0x2014 || cp == 0x2013) return g_font_cp866[0x2D]; // — / –
    if (cp == 0x2026) return g_font_cp866[0x2E]; // …
    if (cp == 0x2022) return g_font_cp866[0x07]; // •

    return g_font_cp866['?'];
}

